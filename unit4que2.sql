CREATE OR REPLACE PROCEDURE SEARCH_STAFF
(
    P_SID IN NUMBER,
    P_NAME OUT VARCHAR2
)
IS
BEGIN
    SELECT SName
    INTO P_NAME
    FROM STAFF
    WHERE SID = P_SID;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20001, 'Staff ID not found.'
        );
END;
/

DECLARE
    V_NAME VARCHAR2(30);
BEGIN
    SEARCH_STAFF(101, V_NAME);

    DBMS_OUTPUT.PUT_LINE('Staff Name: ' || V_NAME);

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(SQLERRM);
END;
/